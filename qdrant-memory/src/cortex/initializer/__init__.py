"""Initializer - Bootstrap repos for code intelligence.

Provides:
- `init` command that sets up everything
- Generates CLAUDE.md, .mcp.json, config
- Optional local Qdrant setup
"""

import json
import os
from pathlib import Path
from typing import Optional


CLAUDE_MD_TEMPLATE = '''# Cortex

This project uses Cortex for LSP-powered code intelligence + hybrid search + memory.

## Quick Start

```
bootstrap()  # One command: activates LSP + indexes project
```

Then ask naturally:
- "Where is the {example_function} function?"
- "Who calls {example_function}?"
- "Find error handling code in src/"

## Golden Path Tools

| Tool | What It Does |
|------|--------------|
| `bootstrap()` | One-command setup |
| `find(query)` | Smart hybrid search |
| `where_is(name)` | Find symbol definition |
| `who_calls(name)` | Find all usages |
| `remember(kind, text)` | Store a memory |
| `recall(query)` | Search memories |
| `doctor()` | System diagnostic |

## Memory Policy

**After completing tasks:**
- **EPISODE** if bugs fixed, solutions found
- **FACT** if learned stable convention
- **RECIPE** if established reusable procedure

## Scoping

Always scope searches:
```python
find(query="auth", path_prefix="{src_dir}")
find(query="test helpers", path_prefix="{test_dir}")
```
'''

MCP_JSON_TEMPLATE = {
    "mcpServers": {
        "cortex": {
            "command": "uvx",
            "args": [
                "cortex-mcp",
                "start-mcp-server",
                "--context", "claude-code",
                "--project", "."
            ],
            "env": {
                "QDRANT_URL": "${QDRANT_URL}",
                "QDRANT_API_KEY": "${QDRANT_API_KEY}"
            }
        }
    }
}

CONFIG_TEMPLATE = '''# Cortex Config
# Generated by: cortex init

# Project settings
project_name: {project_name}
language: {language}

# Indexing
index:
  include:
    - "src/**"
    - "lib/**"
    - "app/**"
  exclude:
    - "node_modules/**"
    - ".git/**"
    - "dist/**"
    - "build/**"
    - "*.min.js"
    - "*.bundle.js"

# Scopes (suggested path prefixes)
scopes:
  source: "{src_dir}"
  tests: "{test_dir}"

# Memory settings
memory:
  default_ttl_days: null  # null = no expiration
  max_episode_age_days: 90
'''


class Initializer:
    """
    Initializes a project for code intelligence.

    Creates:
    - CLAUDE.md with usage instructions
    - .mcp.json for team sharing
    - cortex.yaml config
    """

    def __init__(self, project_path: str):
        self.project_path = Path(project_path).resolve()

    def detect_project_info(self) -> dict:
        """Detect project language and structure."""
        info = {
            "project_name": self.project_path.name,
            "language": "unknown",
            "src_dir": "src/",
            "test_dir": "tests/",
            "example_function": "main",
        }

        # Detect language
        lang_markers = {
            "python": ["pyproject.toml", "setup.py", "requirements.txt"],
            "typescript": ["tsconfig.json"],
            "javascript": ["package.json"],
            "rust": ["Cargo.toml"],
            "go": ["go.mod"],
            "java": ["pom.xml", "build.gradle"],
        }

        for lang, markers in lang_markers.items():
            for marker in markers:
                if (self.project_path / marker).exists():
                    info["language"] = lang
                    break

        # Detect source directory
        for src_candidate in ["src", "lib", "app", "pkg"]:
            if (self.project_path / src_candidate).is_dir():
                info["src_dir"] = f"{src_candidate}/"
                break

        # Detect test directory
        for test_candidate in ["tests", "test", "__tests__", "spec"]:
            if (self.project_path / test_candidate).is_dir():
                info["test_dir"] = f"{test_candidate}/"
                break

        return info

    def init(
        self,
        write_claude_md: bool = True,
        write_mcp_json: bool = True,
        write_config: bool = True,
        force: bool = False,
    ) -> dict:
        """
        Initialize the project.

        Args:
            write_claude_md: Create CLAUDE.md
            write_mcp_json: Create .mcp.json
            write_config: Create cortex.yaml
            force: Overwrite existing files

        Returns:
            {"files_created": list, "files_skipped": list, "info": dict}
        """
        result = {
            "files_created": [],
            "files_skipped": [],
            "info": self.detect_project_info(),
        }

        info = result["info"]

        # CLAUDE.md
        if write_claude_md:
            claude_md_path = self.project_path / "CLAUDE.md"
            if not claude_md_path.exists() or force:
                content = CLAUDE_MD_TEMPLATE.format(**info)
                claude_md_path.write_text(content)
                result["files_created"].append("CLAUDE.md")
            else:
                result["files_skipped"].append("CLAUDE.md (exists)")

        # .mcp.json
        if write_mcp_json:
            mcp_json_path = self.project_path / ".mcp.json"
            if not mcp_json_path.exists() or force:
                mcp_json_path.write_text(json.dumps(MCP_JSON_TEMPLATE, indent=2))
                result["files_created"].append(".mcp.json")
            else:
                result["files_skipped"].append(".mcp.json (exists)")

        # cortex.yaml
        if write_config:
            config_path = self.project_path / "cortex.yaml"
            if not config_path.exists() or force:
                content = CONFIG_TEMPLATE.format(**info)
                config_path.write_text(content)
                result["files_created"].append("cortex.yaml")
            else:
                result["files_skipped"].append("cortex.yaml (exists)")

        return result


def init_command(
    project_path: str = ".",
    force: bool = False,
    no_claude_md: bool = False,
    no_mcp_json: bool = False,
    no_config: bool = False,
) -> dict:
    """
    CLI entrypoint for init command.

    Usage:
        cortex init [path] [--force]
    """
    initializer = Initializer(project_path)
    return initializer.init(
        write_claude_md=not no_claude_md,
        write_mcp_json=not no_mcp_json,
        write_config=not no_config,
        force=force,
    )
